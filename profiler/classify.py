"""Classify every file once (production, test, vendored, generated, data, binary)
and compute the volume and language columns. Every later step reads this list."""
from __future__ import annotations

import fnmatch
import json
import re
import shutil
from collections import defaultdict
from pathlib import Path

from .code import LANGS, NAMED, count_lines, _notebook_code
from .util import log, run

TEST_RE = re.compile(
    r"(^|/)(test|tests|__tests__|spec|specs|testing|e2e|integration[_-]?tests?)(/|$)|"
    r"(^|/)test_[^/]+$|_test\.[a-z0-9]+$|\.(test|spec)\.[a-z0-9]+$|_spec\.[a-z0-9]+$|"
    r"(Test|Tests|Spec|IT)\.(java|kt|kts|cs|scala|swift|php|groovy|m|mm)$|(^|/)conftest\.py$",
    re.I)
GENERATED_NAME_RE = re.compile(
    r"\.pb\.go$|_pb2(_grpc)?\.py$|\.pb\.(cc|h)$|\.g\.dart$|\.freezed\.dart$|\.designer\.cs$|"
    r"\.min\.(js|css)$|[.-]bundle\.js$|\.generated\.[a-z]+$|_generated\.[a-z]+$|\.map$", re.I)
GENERATED_HEADER_RE = re.compile(
    r"code generated .* do not edit|@generated|<auto-generated|autogenerated by|"
    r"this file (is|was) (automatically )?generated|generated by the protocol buffer compiler",
    re.I)
BINARY_EXT = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".bmp", ".webp", ".pdf", ".zip", ".gz",
              ".tar", ".jar", ".war", ".class", ".so", ".dll", ".dylib", ".exe", ".woff",
              ".woff2", ".ttf", ".eot", ".otf", ".mp3", ".mp4", ".mov", ".avi", ".bin", ".dat",
              ".db", ".sqlite", ".pyc", ".o", ".a", ".psd", ".xlsx", ".xls", ".docx", ".pptx"}
EXTRA_LANGS = {".properties": ("Properties File", "#", None, None),
               ".tsv": ("TSV", None, None, None)}
CLASSES = ("production", "test", "vendored", "generated", "data", "binary")


def lang_spec(path: str):
    name = path.rsplit("/", 1)[-1]
    if name in NAMED:
        return NAMED[name]
    ext = ("." + name.rsplit(".", 1)[-1].lower()) if "." in name else ""
    return LANGS.get(ext) or EXTRA_LANGS.get(ext)


def _in_dirs(path: str, dirs: list[str]) -> bool:
    parts = path.split("/")[:-1]
    low = {d.lower() for d in dirs}
    return any(p.lower() in low for p in parts)


def tracked_files(repo: Path) -> list[str]:
    out = run(["git", "ls-files", "-z"], cwd=repo, check=False)
    files = [f for f in out.split("\0") if f]
    if not files:
        files = [str(p.relative_to(repo)).replace("\\", "/") for p in repo.rglob("*")
                 if p.is_file() and ".git" not in p.parts]
    return files


def _venv_roots(repo: Path, files: list[str]) -> set[str]:
    """Folders that hold a committed virtualenv (pyvenv.cfg or lib/pythonX/site-packages)."""
    roots = set()
    for f in files:
        if f.endswith("pyvenv.cfg"):
            roots.add(f.rsplit("/", 1)[0] if "/" in f else "")
        m = re.match(r"(.*?)/lib/python[0-9.]+/site-packages/", f)
        if m:
            roots.add(m.group(1))
    return {r for r in roots if r}


def scc_per_file(repo: Path) -> dict | None:
    """scc --by-file run; None when scc is missing."""
    if not shutil.which("scc"):
        return None
    try:
        raw = json.loads(run(["scc", "--format", "json", "--by-file", "."], cwd=repo, timeout=1800))
    except Exception as e:  # noqa: BLE001
        log.warning("scc failed (%s); using the built in counter", e)
        return None
    out = {}
    for entry in raw:
        for f in entry.get("Files") or []:
            loc = f.get("Location", "").replace("\\", "/")
            loc = loc[2:] if loc.startswith("./") else loc
            out[loc] = {"language": entry["Name"], "lines": f["Lines"], "code": f["Code"],
                        "comment": f["Comment"], "blank": f["Blank"],
                        "generated": bool(f.get("Generated"))}
    return out


def scc_totals(repo: Path, args: list[str]) -> dict | None:
    if not shutil.which("scc"):
        return None
    try:
        raw = json.loads(run(["scc", "--format", "json", *args, "."], cwd=repo, timeout=1800))
    except Exception:  # noqa: BLE001
        return None
    return {"languageSummary": [{k: e[k] for k in ("Name", "Count", "Lines", "Code", "Comment", "Blank")
                                 if k in e} for e in raw],
            "total_code": sum(e["Code"] for e in raw), "total_lines": sum(e["Lines"] for e in raw)}


def read_text(path: Path, max_bytes: int) -> str | None:
    try:
        if path.is_symlink() or not path.is_file() or path.stat().st_size > max_bytes:
            return None
        data = path.read_bytes()
    except OSError:
        return None
    if b"\0" in data[:8000]:
        return None
    return data.decode("utf-8", "replace")


def classify(repo: Path, cfg: dict) -> dict:
    """Returns {'files': [...per file dicts...], 'volume': {...}, 'scc': evidence}."""
    files = tracked_files(repo)
    scc = scc_per_file(repo)
    venvs = _venv_roots(repo, files)
    data_langs = set(cfg["data_languages"])
    lock = set(cfg["lock_files"])
    max_b = cfg["max_file_bytes"]
    rows = []
    for f in files:
        p = repo / f
        name = f.rsplit("/", 1)[-1]
        ext = ("." + name.rsplit(".", 1)[-1].lower()) if "." in name else ""
        try:
            size = p.stat().st_size if p.is_file() else 0
        except OSError:
            size = 0
        spec = lang_spec(f)
        info = scc.get(f) if scc else None
        text = None
        if info is None:
            if ext in BINARY_EXT:
                lang, lines, code, comment, blank = "", 0, 0, 0, 0
            else:
                text = read_text(p, 50_000_000)
                if text is None:
                    lang, lines, code, comment, blank = "", 0, 0, 0, 0
                    ext = ext or ".bin"
                elif spec:
                    if spec[0] == "Jupyter":
                        text_for_count = _notebook_code(text)
                    else:
                        text_for_count = text
                    code, comment, blank = count_lines(text_for_count, spec)
                    lang, lines = spec[0], code + comment + blank
                else:
                    lang, lines, code, comment, blank = "", 0, 0, 0, 0
        else:
            lang, lines, code, comment, blank = (info["language"], info["lines"], info["code"],
                                                 info["comment"], info["blank"])
        # ---- class
        if (ext in BINARY_EXT or (not lang and size and text is None)) and not info:
            cls = "binary"
        elif _in_dirs(f, cfg["vendored_dirs"]) or any(f.startswith(v + "/") for v in venvs):
            cls = "vendored"
        elif (name in lock or GENERATED_NAME_RE.search(f) or _in_dirs(f, cfg["generated_dirs"])
              or (info and info.get("generated"))):
            cls = "generated"
        elif lang in data_langs:
            cls = "data"
        elif TEST_RE.search(f):
            cls = "test"
        elif lang:
            cls = "production"
        else:
            cls = "data" if size else "binary"
        if cls in ("production", "test") and lang and code:
            head = text if text is not None else read_text(p, max_b)
            if head and GENERATED_HEADER_RE.search(head[:2000]):
                cls = "generated"
        rows.append({"path": f, "class": cls, "language": lang, "lines": lines, "code_loc": code,
                     "comment": comment, "blank": blank, "size": size,
                     "scc_counted": info is not None,   # False for files scc skips (lock files, .gitignore, .cfg)
                     "excluded": _in_dirs(f, cfg["excluded_dirs"]) or any(
                         f.startswith(v + "/") for v in venvs)})
    return {"files": rows, "volume": volume(rows, cfg), "scc_used": scc is not None,
            "venv_roots": sorted(venvs)}


def volume(rows: list[dict], cfg: dict) -> dict:
    data_langs = set(cfg["data_languages"])
    kept = [r for r in rows if not r["excluded"]]
    # Like "scc .": every tracked text file counts, vendored and generated included.
    logical = sum(r["code_loc"] for r in rows)
    physical = sum(r["lines"] for r in rows)
    data_loc = sum(r["code_loc"] for r in rows if r["language"] in data_langs)
    non_authored = sum(r["code_loc"] for r in rows if r["class"] in ("vendored", "generated"))
    prod = [r for r in rows if r["class"] == "production"]
    test = [r for r in rows if r["class"] == "test"]
    by_lang: dict[str, int] = defaultdict(int)
    data_by_lang: dict[str, int] = defaultdict(int)
    for r in rows:
        if r["class"] == "production" and r["language"] not in data_langs:
            by_lang[r["language"]] += r["code_loc"]
        elif r["class"] in ("production", "data", "test") and r["language"] in data_langs:
            data_by_lang[r["language"]] += r["code_loc"]
    total_code = sum(by_lang.values())
    total_all = total_code + sum(data_by_lang.values())
    # One denominator (code + data LOC of the repo's own files), code languages first,
    # data and markup after the bar, so the numbers add up to about 100%.
    breakdown = "; ".join(f"{k}:{v / total_all * 100:.1f}%" for k, v in
                          sorted(by_lang.items(), key=lambda kv: -kv[1]) if total_all and v / total_all >= 0.001)
    data_part = "; ".join(f"{k}:{v / total_all * 100:.1f}%" for k, v in
                          sorted(data_by_lang.items(), key=lambda kv: -kv[1]) if total_all and v / total_all >= 0.001)
    if data_part:
        breakdown = f"{breakdown} | {data_part}" if breakdown else f"| {data_part}"
    primary = max(by_lang.items(), key=lambda kv: kv[1])[0] if by_lang else ""
    return {
        "total_files": len(kept),
        "size_kb": round(sum(r["size"] for r in kept) / 1024),
        "source_files": len(prod),
        "test_files": len(test),
        "physical_loc": physical,
        "logical_loc": logical,
        "data_markup_loc": data_loc,
        "non_authored_loc": min(non_authored, logical),
        "source_loc": sum(r["code_loc"] + r["comment"] for r in prod),
        "test_loc": sum(r["code_loc"] + r["comment"] for r in test),
        "primary_language": primary,
        "language_breakdown": breakdown,
        "category": "Rare language" if primary in set(cfg["rare_languages"]) else ("General" if primary else ""),
        "production_code_loc": total_code,
        "lang_code_loc": dict(by_lang),
    }


SCC_GENERATED_ARGS = ["--no-gen", "--no-min-gen", "--exclude-dir",
                      "vendor,node_modules,dist,build,generated,migrations"]
SCC_GENERATED_CMD = "scc --format json " + " ".join(SCC_GENERATED_ARGS) + " ."


def non_authored_scc(repo: Path, cfg: dict, rows: list[dict]) -> dict | None:
    """the buyer's method: scc . minus scc with generated and minified files ignored and vendor
    directories excluded, plus lock files and committed virtualenvs. Returns evidence or None
    when scc is missing. (scc flags: --no-gen drops files with a generated marker, --no-min-gen
    drops minified files; there is no --generated-code flag in any scc release.)"""
    default = scc_totals(repo, [])
    if default is None:
        return None
    lock = set(cfg["lock_files"])
    extra = sum(r["code_loc"] for r in rows if r["path"].rsplit("/", 1)[-1] in lock)
    venv = sum(r["code_loc"] for r in rows if r["class"] == "vendored" and r["excluded"]
               and "site-packages" in r["path"])
    gen = scc_totals(repo, SCC_GENERATED_ARGS)
    if gen is None:
        # Keep scc's totals for Logical and Physical LOC, but take the non-authored figure
        # from the file classes so one failed scc call never fails the whole repo.
        builtin = sum(r["code_loc"] for r in rows if r["class"] in ("vendored", "generated"))
        log.warning("scc generated-code run failed in %s; non-authored LOC from file classes", repo.name)
        return {"default_run": {"command": "scc --format json .", **default},
                "generated_run": {"command": SCC_GENERATED_CMD, "error": "scc call failed",
                                  "total_code": default["total_code"] - builtin},
                "lock_file_loc": extra, "lock_files_in_logical_loc": False,
                "committed_venv_loc": venv,
                "non_authored_loc": min(builtin - extra, default["total_code"]),
                "non_authored_source": "file classes (scc generated run failed)"}
    # scc skips lock files by default (its --exclude-file list), so they are in neither run and
    # not in Logical LOC either. They are reported for transparency but not added, so that
    # Non-Authored LOC stays a subset of Logical LOC. Committed virtualenvs are in both runs
    # (site-packages is not in the exclude list), so they are added.
    na = max(0, default["total_code"] - gen["total_code"]) + venv
    return {"default_run": {"command": "scc --format json .", **default},
            "generated_run": {"command": SCC_GENERATED_CMD, "total_code": gen["total_code"]},
            "lock_file_loc": extra, "lock_files_in_logical_loc": False,
            "committed_venv_loc": venv,
            "non_authored_loc": min(na, default["total_code"]),
            "non_authored_source": "scc"}


def write_file_classes(rows: list[dict], path: Path) -> None:
    import csv
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["path", "class", "language", "code_loc"])
        for r in rows:
            w.writerow([r["path"], r["class"], r["language"], r["code_loc"]])


def matches_any(path: str, globs: list[str]) -> bool:
    return any(fnmatch.fnmatch(path, g) for g in globs)
